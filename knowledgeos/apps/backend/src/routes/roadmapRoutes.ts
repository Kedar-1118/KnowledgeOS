// apps/backend/src/routes/roadmapRoutes.ts
import { Router, type Request, type Response } from 'express';
import { jwtMiddleware } from '../auth/jwtMiddleware.js';
import { prisma } from '../utils/prisma.js';
import { getLLMProvider } from '../services/llm/llmProvider.js';
import { logger } from '../utils/logger.js';

export const roadmapRouter = Router();

roadmapRouter.use(jwtMiddleware);

/**
 * POST /api/roadmaps
 * Generate a new learning roadmap for a topic.
 */
roadmapRouter.post('/', async (req: Request, res: Response) => {
  try {
    if (!req.user) {
      res.status(401).json({ success: false, error: { code: 'UNAUTHORIZED', message: 'Not authenticated' } });
      return;
    }

    const { topic } = req.body as { topic: string };
    if (!topic?.trim()) {
      res.status(400).json({ success: false, error: { code: 'BAD_REQUEST', message: 'Topic is required' } });
      return;
    }

    const userId = req.user.id;
    const provider = getLLMProvider();

    logger.info(`Generating roadmap for topic: ${topic} for user ${userId}...`);
    const nodes = await provider.createRoadmap(topic);

    if (!Array.isArray(nodes) || nodes.length === 0) {
      res.status(500).json({ success: false, error: { code: 'ROADMAP_GEN_FAILED', message: 'No nodes generated by LLM' } });
      return;
    }

    // 1. Create learning roadmap parent
    const roadmap = await prisma.learningRoadmap.create({
      data: {
        userId,
        title: topic,
      },
    });

    // 2. Insert nodes first without parent link
    const nodeMap = new Map<string, string>();
    for (const node of nodes) {
      const createdNode = await prisma.roadmapNode.create({
        data: {
          roadmapId: roadmap.id,
          label: node.label,
          type: node.type || 'CORE',
          status: 'PLANNED',
          order: node.order || 0,
        },
      });
      nodeMap.set(node.label, createdNode.id);
    }

    // 3. Update nodes with parent links
    for (const node of nodes) {
      if (node.parentLabel && nodeMap.has(node.parentLabel)) {
        const childId = nodeMap.get(node.label)!;
        const parentId = nodeMap.get(node.parentLabel)!;
        await prisma.roadmapNode.update({
          where: { id: childId },
          data: { parentNodeId: parentId },
        });
      }
    }

    // Fetch full roadmap with nodes to return
    const completedRoadmap = await prisma.learningRoadmap.findUnique({
      where: { id: roadmap.id },
      include: {
        nodes: {
          orderBy: { order: 'asc' },
        },
      },
    });

    res.json({ success: true, data: completedRoadmap });
  } catch (error: any) {
    logger.error('Failed to create roadmap:', error);
    res.status(500).json({ success: false, error: { code: 'ROADMAP_FAILED', message: error.message } });
  }
});

/**
 * GET /api/roadmaps
 * List all roadmaps for the user.
 */
roadmapRouter.get('/', async (req: Request, res: Response) => {
  try {
    if (!req.user) {
      res.status(401).json({ success: false, error: { code: 'UNAUTHORIZED', message: 'Not authenticated' } });
      return;
    }

    const roadmaps = await prisma.learningRoadmap.findMany({
      where: { userId: req.user.id },
      include: {
        _count: {
          select: { nodes: true },
        },
      },
      orderBy: { createdAt: 'desc' },
    });

    res.json({ success: true, data: roadmaps });
  } catch (error: any) {
    logger.error('Failed to list roadmaps:', error);
    res.status(500).json({ success: false, error: { code: 'ROADMAP_FAILED', message: error.message } });
  }
});

/**
 * GET /api/roadmaps/:id
 * Retrieve details of a specific roadmap including its nodes.
 */
roadmapRouter.get('/:id', async (req: Request, res: Response) => {
  try {
    if (!req.user) {
      res.status(401).json({ success: false, error: { code: 'UNAUTHORIZED', message: 'Not authenticated' } });
      return;
    }

    const roadmap = await prisma.learningRoadmap.findFirst({
      where: { id: req.params.id, userId: req.user.id },
      include: {
        nodes: {
          orderBy: { order: 'asc' },
        },
      },
    });

    if (!roadmap) {
      res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Roadmap not found' } });
      return;
    }

    res.json({ success: true, data: roadmap });
  } catch (error: any) {
    logger.error('Failed to get roadmap detail:', error);
    res.status(500).json({ success: false, error: { code: 'ROADMAP_FAILED', message: error.message } });
  }
});

/**
 * PATCH /api/roadmaps/nodes/:nodeId
 * Update a node's completion status.
 */
roadmapRouter.patch('/nodes/:nodeId', async (req: Request, res: Response) => {
  try {
    if (!req.user) {
      res.status(401).json({ success: false, error: { code: 'UNAUTHORIZED', message: 'Not authenticated' } });
      return;
    }

    const { status } = req.body as { status: 'PLANNED' | 'IN_PROGRESS' | 'COMPLETED' };
    const { nodeId } = req.params;

    // Verify node belongs to user's roadmap
    const node = await prisma.roadmapNode.findFirst({
      where: {
        id: nodeId,
        roadmap: { userId: req.user.id },
      },
    });

    if (!node) {
      res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Node not found' } });
      return;
    }

    const updatedNode = await prisma.roadmapNode.update({
      where: { id: nodeId },
      data: { status },
    });

    res.json({ success: true, data: updatedNode });
  } catch (error: any) {
    logger.error('Failed to update node status:', error);
    res.status(500).json({ success: false, error: { code: 'NODE_UPDATE_FAILED', message: error.message } });
  }
});

/**
 * DELETE /api/roadmaps/:id
 * Delete a specific roadmap.
 */
roadmapRouter.delete('/:id', async (req: Request, res: Response) => {
  try {
    if (!req.user) {
      res.status(401).json({ success: false, error: { code: 'UNAUTHORIZED', message: 'Not authenticated' } });
      return;
    }

    const roadmap = await prisma.learningRoadmap.findFirst({
      where: { id: req.params.id, userId: req.user.id },
    });

    if (!roadmap) {
      res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Roadmap not found' } });
      return;
    }

    await prisma.learningRoadmap.delete({
      where: { id: roadmap.id },
    });

    res.json({ success: true, message: 'Roadmap deleted successfully' });
  } catch (error: any) {
    logger.error('Failed to delete roadmap:', error);
    res.status(500).json({ success: false, error: { code: 'ROADMAP_DELETE_FAILED', message: error.message } });
  }
});
